/// Демо-режим: заказы, вход, корзина и чат работают на моках, без бэкенда.
///
/// Это НЕ отладочный флаг, который забыли выключить, — заказчице показывают
/// готовые экраны до того, как поднят сервер, поэтому умолчание именно `true`.
/// Боевая сборка выключает его флагом, без правки кода:
///
/// ```
/// flutter run --dart-define=DEMO=false
/// ```
const bool kDemoMode = bool.fromEnvironment('DEMO', defaultValue: true);

/// Контент (товары, цены, фото, отели, суммы, бренд, баннеры) берётся из
/// админки через `GET /app/config`.
///
/// В боевой сборке — всегда. В демо — когда при сборке указан адрес сервера:
///
/// ```
/// flutter build web --dart-define=API_BASE_URL=https://api.turtuk.example.com
/// ```
///
/// Тогда заказчица меняет цену или фото в админке и видит это в демо, хотя
/// заказы в нём по-прежнему тестовые. Без адреса демо берёт контент из ассетов.
const bool kContentFromApi = !kDemoMode || bool.hasEnvironment('API_BASE_URL');
