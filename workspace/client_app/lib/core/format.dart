import 'package:intl/intl.dart';

/// Формат цены: «1 250 ₽», разделитель разрядов — НЕРАЗРЫВНЫЙ пробел (U+00A0).
///
/// Обычный пробел здесь ломает вёрстку карточки товара: строка «1 250 ₽»
/// переносится между «1» и «250», и цена читается как два разных числа.
/// `intl` для русской локали и так ставит неразрывный, но полагаться на это
/// нельзя — формат зависит от загруженных данных локали, а цена показывается
/// одинаково во всех трёх языках приложения.
final NumberFormat _rub = NumberFormat.decimalPattern('ru_RU');

String money(double v) {
  final rounded = v.roundToDouble();
  // Копейки в каталоге не встречаются (цены целые), поэтому дробная часть
  // не печатается вовсе: «1 250 ₽» вместо «1 250,00 ₽».
  final digits = _rub.format(rounded.abs().toInt()).replaceAll(' ', '\u00A0');
  final sign = rounded < 0 ? '\u2212' : '';
  return '$sign$digits\u00A0₽';
}
